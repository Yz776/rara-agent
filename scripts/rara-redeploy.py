#!/usr/bin/env python3
"""
Redeploy rara-agent to port 3002 with HOSTNAME=0.0.0.0 + DATABASE_URL set.

This script assumes the previous deploy already extracted the source tarball
and built .next/standalone/. We just need to:
  1. Re-upload the fixed ecosystem.config.cjs.
  2. Check / create /opt/rara-agent/.env with the required secrets.
  3. pm2 delete + restart rara-web.
  4. Wait + verify rara.ai.id responds with Rara HTML (not the WhatsApp bot).
"""

import os
import sys
import stat
import paramiko

HOST = os.environ.get("RARA_HOST", "209.50.50.121")
USER = os.environ.get("RARA_USER", "root")
PASS = os.environ.get("RARA_PASS", "")
LOCAL_ECOSYSTEM = "/home/z/my-project/ecosystem.config.cjs"
REMOTE_ECOSYSTEM = "/opt/rara-agent/ecosystem.config.cjs"
REMOTE_ENV = "/opt/rara-agent/.env"

if not PASS:
    print("ERROR: set RARA_PASS env var first", file=sys.stderr)
    sys.exit(2)


def run(client: paramiko.SSHClient, cmd: str, timeout: int = 60) -> tuple[int, str, str]:
    print(f"$ {cmd}")
    stdin, stdout, stderr = client.exec_command(cmd, timeout=timeout)
    out = stdout.read().decode("utf-8", "replace")
    err = stderr.read().decode("utf-8", "replace")
    code = stdout.channel.recv_exit_status()
    if out.strip():
        print(out.rstrip()[:2000])
    if err.strip():
        print(f"[stderr] {err.rstrip()[:1500]}")
    if code != 0:
        print(f"[exit={code}]")
    return code, out, err


def docker_run(client: paramiko.SSHClient, cmd: str, timeout: int = 60) -> tuple[int, str, str]:
    return run(client, f"docker exec kali sh -c {cmd!r}", timeout=timeout)


def sftp_upload(client: paramiko.SSHClient, local: str, remote: str) -> None:
    print(f"→ sftp {local} → {remote}")
    sftp = client.open_sftp()
    try:
        sftp.put(local, remote)
        lsize = os.path.getsize(local)
        rsize = sftp.stat(remote).st_size
        print(f"  ✓ uploaded {lsize} bytes (verified {rsize})")
    finally:
        sftp.close()


def main() -> int:
    print(f"→ connecting to {USER}@{HOST}")
    client = paramiko.SSHClient()
    client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    client.connect(hostname=HOST, username=USER, password=PASS, timeout=20)

    # ── 1. Check existing .env on server ──────────────────────────────────────
    print("\n→ reading current /opt/rara-agent/.env")
    code, out, _ = docker_run(client, "cat /opt/rara-agent/.env 2>&1")
    existing_env = out if code == 0 and "No such file" not in out else ""

    # Parse existing key=value lines
    env_vars: dict[str, str] = {}
    for line in existing_env.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        k, _, v = line.partition("=")
        env_vars[k.strip()] = v.strip().strip('"').strip("'")

    print(f"  found {len(env_vars)} env vars: {sorted(env_vars.keys())}")

    # ── 2. Generate missing secrets ───────────────────────────────────────────
    import secrets
    import base64

    needed = {
        "KFAI_AUTH_SECRET": lambda: secrets.token_hex(24),
        "KROUTER_ADMIN_PASSWORD": lambda: base64.b64encode(secrets.token_bytes(18)).decode("ascii").rstrip("="),
    }
    for key, gen in needed.items():
        if key not in env_vars or not env_vars[key]:
            new_val = gen()
            env_vars[key] = new_val
            print(f"  ✓ generated new {key} ({len(new_val)} chars)")

    # Force these to correct values for the kali-linux deployment
    env_vars["DATABASE_URL"] = "file:/app/db/rara.db"
    env_vars["KROUTER_ADMIN_USERNAME"] = env_vars.get("KROUTER_ADMIN_USERNAME", "admin")
    env_vars["NODE_ENV"] = "production"

    # ── 3. Write .env back to server ───────────────────────────────────────────
    new_env_lines = [
        "# Rara Agent — runtime env (regenerated by rara-redeploy.py)",
        "# All values are read by PM2 when launching rara-web (see ecosystem.config.cjs).",
        "",
    ]
    for k in sorted(env_vars):
        v = env_vars[k]
        # Quote values that contain special chars
        if any(c in v for c in " #\"'"):
            new_env_lines.append(f'{k}="{v}"')
        else:
            new_env_lines.append(f"{k}={v}")
    new_env_text = "\n".join(new_env_lines) + "\n"

    print("\n→ writing new /opt/rara-agent/.env")
    # Write locally to /tmp first then sftp put
    tmp_env = "/home/z/my-project/scripts/rara.env.tmp"
    with open(tmp_env, "w", encoding="utf-8") as f:
        f.write(new_env_text)
    sftp = client.open_sftp()
    try:
        # SFTP can't write directly into docker container — write to host /tmp
        # then docker cp into the container.
        sftp.put(tmp_env, "/tmp/rara.env")
    finally:
        sftp.close()
    run(client, "docker cp /tmp/rara.env kali:/opt/rara-agent/.env")
    docker_run(client, "chmod 600 /opt/rara-agent/.env && ls -la /opt/rara-agent/.env")

    # Also persist the secrets to a host-side file so we can show them to the user.
    secrets_path = "/home/z/my-project/scripts/rara-secrets.txt"
    with open(secrets_path, "w", encoding="utf-8") as f:
        f.write("# Rara Agent secrets — generated by rara-redeploy.py\n")
        f.write(f"# Server: {HOST} (container: kali, path: /opt/rara-agent/.env)\n")
        f.write(f"# Generated: 2026-10-20\n\n")
        for k in sorted(env_vars):
            f.write(f"{k}={env_vars[k]}\n")
    print(f"\n→ secrets saved to {secrets_path}")

    # ── 4. Upload the fixed ecosystem.config.cjs ──────────────────────────────
    print("\n→ uploading fixed ecosystem.config.cjs")
    sftp_upload(client, LOCAL_ECOSYSTEM, "/tmp/ecosystem.config.cjs")
    run(client, "docker cp /tmp/ecosystem.config.cjs kali:/opt/rara-agent/ecosystem.config.cjs")

    # ── 5. Push Prisma DB schema (so the SQLite file has tables) ──────────────
    print("\n→ pushing Prisma schema")
    docker_run(
        client,
        "cd /opt/rara-agent && DATABASE_URL='file:/app/db/rara.db' npx prisma db push --accept-data-loss 2>&1 | tail -20",
        timeout=120,
    )

    # ── 6. Restart rara-web ───────────────────────────────────────────────────
    print("\n→ restarting rara-web PM2 process")
    docker_run(client, "pm2 delete rara-web 2>&1 || true")
    # Source env vars into the pm2 start command so ecosystem.config.cjs picks them up.
    docker_run(
        client,
        "cd /opt/rara-agent && set -a && . ./.env && set +a && pm2 start ecosystem.config.cjs 2>&1 | tail -15",
        timeout=60,
    )
    docker_run(client, "pm2 save 2>&1 | tail -5")

    # ── 7. Wait + verify ──────────────────────────────────────────────────────
    print("\n→ waiting 12s for rara-web to settle")
    import time
    time.sleep(12)

    print("\n→ verification (port 3002 = rara.ai.id, port 3000 = WhatsApp bot)")
    docker_run(client, "pm2 list 2>&1 | grep -E 'rara-web|name|id '")
    docker_run(client, "ss -tlnp 2>&1 | grep -E ':300[0-9]'")
    code, out, _ = docker_run(
        client,
        "curl -s -o /dev/null -w 'port3002 http=%{http_code} size=%{size_download} time=%{time_total}\\n' http://127.0.0.1:3002/",
    )
    if "http=200" in out:
        print("  ✓ rara-web (port 3002) returned 200")
    else:
        print(f"  ! port 3002: {out}")
    code, out, _ = docker_run(
        client,
        "curl -s http://127.0.0.1:3002/ | head -c 300",
    )
    print(f"  preview: {out}")
    # Confirm it's Rara, not WhatsApp bot
    if "Rara" in out or "ceria" in out.lower() or "rara-welcome" in out:
        print("  ✓ Rara HTML confirmed on port 3002")
    elif "WhatsApp" in out:
        print("  ✗ port 3002 is still serving WhatsApp bot HTML — nginx upstream may be wrong")
    else:
        print(f"  ? unexpected HTML on port 3002 (size {len(out)})")

    # ── 8. Final pm2 logs ──────────────────────────────────────────────────────
    print("\n→ pm2 logs rara-web (last 25 lines)")
    docker_run(client, "pm2 logs rara-web --lines 25 --nostream 2>&1 | tail -30")

    # ── 9. External domain probe ──────────────────────────────────────────────
    print("\n→ probing rara.ai.id from server (external view)")
    code, out, _ = run(
        client,
        "curl -sk -o /dev/null -w 'https://rara.ai.id/ http=%{http_code} size=%{size_download}\\n' https://rara.ai.id/",
        timeout=20,
    )
    if "http=200" in out:
        print("  ✓ https://rara.ai.id/ returned 200")

    client.close()

    # Show the secrets to the user.
    print("\n" + "=" * 70)
    print("RARA AGENT SECRETS — copy these somewhere safe (also in scripts/rara-secrets.txt)")
    print("=" * 70)
    for k in sorted(env_vars):
        v = env_vars[k]
        if k in ("KFAI_AUTH_SECRET", "KROUTER_ADMIN_PASSWORD"):
            print(f"  {k} = {v}")
        else:
            print(f"  {k} = {v}")
    print("=" * 70)

    print("\n✓ redeploy complete")
    return 0


if __name__ == "__main__":
    sys.exit(main())

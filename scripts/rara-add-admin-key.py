#!/usr/bin/env python3
"""
Add KF_AI_ADMIN_KEY to /opt/rara-agent/.env, restart rara-web, verify.

Also probes /api/auth with a real browser User-Agent to confirm the bot-blocker
is what was causing the previous "Bad Gateway" responses.
"""

import os
import sys
import secrets
import time
import paramiko

HOST = os.environ.get("RARA_HOST", "209.50.50.121")
USER = os.environ.get("RARA_USER", "root")
PASS = os.environ.get("RARA_PASS", "")

if not PASS:
    sys.exit(2)

client = paramiko.SSHClient()
client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
client.connect(hostname=HOST, username=USER, password=PASS, timeout=20)


def run(cmd: str, timeout: int = 60) -> tuple[int, str, str]:
    print(f"$ {cmd[:240]}")
    stdin, stdout, stderr = client.exec_command(cmd, timeout=timeout)
    out = stdout.read().decode("utf-8", "replace")
    err = stderr.read().decode("utf-8", "replace")
    code = stdout.channel.recv_exit_status()
    if out.strip():
        print(out.rstrip()[:1500])
    if err.strip():
        print(f"[stderr] {err.rstrip()[:800]}")
    print()
    return code, out, err


def docker(cmd: str, timeout: int = 60) -> tuple[int, str, str]:
    return run(f"docker exec kali sh -c {cmd!r}", timeout=timeout)


# 1. Generate a fresh KF_AI_ADMIN_KEY
new_admin_key = secrets.token_urlsafe(48)
print(f"→ generated KF_AI_ADMIN_KEY ({len(new_admin_key)} chars): {new_admin_key[:30]}...")

# 2. Append KF_AI_ADMIN_KEY to .env (idempotent — replace if exists)
# Read current .env, modify, write back.
code, current_env, _ = docker("cat /opt/rara-agent/.env 2>&1")
new_lines = []
saw_admin_key = False
for line in current_env.splitlines():
    if line.startswith("KF_AI_ADMIN_KEY="):
        new_lines.append(f"KF_AI_ADMIN_KEY={new_admin_key}")
        saw_admin_key = True
    else:
        new_lines.append(line)
if not saw_admin_key:
    new_lines.append("")
    new_lines.append("# Admin panel X-Admin-Key (for /api/admin/* endpoints). Generated by rara-add-admin-key.py")
    new_lines.append(f"KF_AI_ADMIN_KEY={new_admin_key}")

new_env_text = "\n".join(new_lines) + "\n"

# Write to host /tmp first, then docker cp.
tmp_path = "/home/z/my-project/scripts/rara.env.tmp"
with open(tmp_path, "w", encoding="utf-8") as f:
    f.write(new_env_text)

sftp = client.open_sftp()
sftp.put(tmp_path, "/tmp/rara.env")
sftp.close()
run("docker cp /tmp/rara.env kali:/opt/rara-agent/.env")
docker("chmod 600 /opt/rara-agent/.env")

# Show what's in .env now (mask secrets)
code, out, _ = docker("cat /opt/rara-agent/.env")
print("Current .env (redacted):")
for line in out.splitlines():
    if "=" in line and not line.startswith("#"):
        k, _, v = line.partition("=")
        if any(s in k for s in ("SECRET", "PASSWORD", "KEY", "TOKEN")):
            print(f"  {k} = {v[:8]}...{v[-4:] if len(v) > 12 else ''}")
        else:
            print(f"  {k} = {v}")
    else:
        print(f"  {line}")
print()

# 3. Restart rara-web to pick up new env
print("→ restarting rara-web")
docker("pm2 delete rara-web 2>&1 || true")
docker("cd /opt/rara-agent && set -a && . ./.env && set +a && pm2 start ecosystem.config.cjs 2>&1 | tail -10")
docker("pm2 save 2>&1 | tail -3")

# 4. Wait for startup
print("\n→ waiting 12s for rara-web to settle")
time.sleep(12)

# 5. Verify with REAL browser User-Agent (the bot-blocker checks UA)
ua = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/132.0.0.0 Safari/537.36"
print(f"\n→ probing /api/auth with browser UA")
docker(
    f"curl -sS -X POST http://127.0.0.1:3002/api/auth -H 'Content-Type: application/json' -H 'User-Agent: {ua}' -d '{{\"_fp\":\"test-fp-12345678901234567890\",\"_bh\":\"m:0,v:0,var:0,k:0,kt:0,s:0,t:0\",\"_ts\":2}}' --max-time 15 | head -c 500"
)

# 6. Test the admin key against /api/admin/users
print("\n→ probing /api/admin/users with new X-Admin-Key")
docker(
    f"curl -sS http://127.0.0.1:3002/api/admin/users -H 'User-Agent: {ua}' -H 'X-Admin-Key: {new_admin_key}' --max-time 10 | head -c 500"
)
print("\n→ probing /api/admin/users WITHOUT admin key (should 401)")
docker(
    f"curl -sS http://127.0.0.1:3002/api/admin/users -H 'User-Agent: {ua}' --max-time 10 | head -c 200"
)

# 7. External domain probe
print("\n→ probing https://rara.ai.id/ (external)")
run(
    f"curl -sk -o /dev/null -w 'http=%{{http_code}} size=%{{size_download}}\\n' -H 'User-Agent: {ua}' https://rara.ai.id/",
    timeout=20,
)

# 8. Final pm2 status
print("\n→ pm2 status")
docker("pm2 list 2>&1 | grep -E 'rara|name|id '")
docker("ss -tlnp 2>&1 | grep -E ':300[0-9]'")

# 9. Save the admin key to a local file for the user
secrets_path = "/home/z/my-project/scripts/rara-secrets.txt"
# Append the admin key
with open(secrets_path, "a", encoding="utf-8") as f:
    f.write(f"\n# Added by rara-add-admin-key.py\n")
    f.write(f"KF_AI_ADMIN_KEY={new_admin_key}\n")
print(f"\n→ admin key appended to {secrets_path}")

print("\n" + "=" * 70)
print("ADMIN PANEL KEY (use as X-Admin-Key header for /api/admin/*)")
print("=" * 70)
print(f"  KF_AI_ADMIN_KEY = {new_admin_key}")
print("=" * 70)
print(f"\nAdmin panel URL: https://rara.ai.id/admin")
print(f"Admin username: admin")
print(f"Admin password: see KROUTER_ADMIN_PASSWORD in {secrets_path}")
print(f"Admin API key: {new_admin_key}")
print()
print("Usage examples:")
print("  curl -H 'X-Admin-Key: " + new_admin_key + "' https://rara.ai.id/api/admin/users")
print("  curl -H 'X-Admin-Key: " + new_admin_key + "' https://rara.ai.id/api/admin/stats")

client.close()
print("\n✓ admin key configured")

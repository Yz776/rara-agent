#!/usr/bin/env python3
"""
Install real nginx in running container + configure reverse proxy for all domains.
Domains:
  rara.ai.id           → port 3002 (rara-web Next.js)
  storage.kangwifi.eu.org → port 47291 (cloud-storage)
  game.kangwifi.eu.org  → port 3000 (catur/bot-amd64)
  wotanime.my.id        → port 3051 (animest)
"""
import paramiko, time

client = paramiko.SSHClient()
client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
client.connect(hostname="209.50.50.121", username="root", password="REDACTED_WIFI_PASS",
               timeout=15, allow_agent=False, look_for_keys=False)

# Step 1: Install nginx in the running container
print("=== Step 1: Install nginx in running container ===", flush=True)
stdin, stdout, stderr = client.exec_command(
    "docker exec kali bash -c 'apt update -qq && DEBIAN_FRONTEND=noninteractive apt install -y nginx 2>&1 | tail -5'",
    timeout=120
)
print(stdout.read().decode("utf-8", errors="replace"))

# Step 2: Write nginx config for all domains
print("\n=== Step 2: Write nginx reverse proxy config ===", flush=True)

nginx_config = r'''# Rara Agent + Kali-Linux reverse proxy
# Generated by rara-mega-deploy script

# Upstream apps
upstream rara_web { server 127.0.0.1:3002; }
upstream cloud_storage { server 127.0.0.1:47291; }
upstream game_arena { server 127.0.0.1:3000; }
upstream animest { server 127.0.0.1:3051; }

# HTTP → reverse proxy (Cloudflare handles HTTPS termination)
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;

    # Rara AI chat (main domain)
    location / {
        proxy_pass http://rara_web;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
    }
}

# storage.kangwifi.eu.org → cloud-storage
server {
    listen 80;
    listen [::]:80;
    server_name storage.kangwifi.eu.org;

    location / {
        proxy_pass http://cloud_storage;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }
}

# game.kangwifi.eu.org → catur/game arena
server {
    listen 80;
    listen [::]:80;
    server_name game.kangwifi.eu.org;

    location / {
        proxy_pass http://game_arena;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
    }
}

# wotanime.my.id → animest
server {
    listen 80;
    listen [::]:80;
    server_name wotanime.my.id;

    location / {
        proxy_pass http://animest;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
    }
}
'''

# Upload nginx config via SFTP
sftp = client.open_sftp()
with sftp.file('/tmp/rara-nginx.conf', 'w') as f:
    f.write(nginx_config)
print("  nginx config uploaded", flush=True)
sftp.close()

# Step 3: Apply nginx config + stop stub + start real nginx
print("\n=== Step 3: Apply config + start nginx ===", flush=True)
stdin, stdout, stderr = client.exec_command(
    # Copy config into container
    "docker cp /tmp/rara-nginx.conf kali:/etc/nginx/conf.d/rara-nginx.conf; "
    # Stop the nginx STUB in PM2 (it's just sleep infinity)
    "docker exec kali pm2 stop nginx 2>&1 | head -3; "
    "docker exec kali pm2 delete nginx 2>&1 | head -3; "
    # Test nginx config
    "docker exec kali nginx -t 2>&1; "
    # Start real nginx
    "docker exec kali nginx 2>&1; "
    "sleep 3; "
    # Verify nginx is listening on port 80
    "echo; echo '=== ports after nginx start ==='; "
    "ss -tlnp | grep -E ':(80|443|3002|3001|8090|47291)' | head -10; "
    "echo; echo '=== HTTP tests ==='; "
    # Test with Host header to simulate domain
    "for DOMAIN_HOST in 'rara.ai.id' 'storage.kangwifi.eu.org' 'game.kangwifi.eu.org' 'wotanime.my.id'; do "
    "  CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 -H \"Host: $DOMAIN_HOST\" http://localhost:80/ 2>/dev/null); "
    "  echo \"  $DOMAIN_HOST → HTTP $CODE\"; "
    "done; "
    "echo; echo '=== direct port tests ==='; "
    "for PORT in 3002 47291 8090 3000; do "
    "  CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 3 http://localhost:$PORT/ 2>/dev/null); "
    "  echo \"  port $PORT → HTTP $CODE\"; "
    "done",
    timeout=60
)
print(stdout.read().decode("utf-8", errors="replace"))

# Step 4: Also check if Cloudflare can reach the server
print("\n=== Step 4: Test from outside (via curl to domains) ===", flush=True)
stdin, stdout, stderr = client.exec_command(
    "echo '=== External access test ==='; "
    "for DOMAIN in rara.ai.id storage.kangwifi.eu.org game.kangwifi.eu.org wotanime.my.id; do "
    "  CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 https://$DOMAIN/ 2>/dev/null); "
    "  echo \"  https://$DOMAIN → HTTP $CODE\"; "
    "done",
    timeout=60
)
print(stdout.read().decode("utf-8", errors="replace"))
client.close()
